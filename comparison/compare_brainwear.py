def make_figure(data: dict, scores: list[str], title: str, out_stub):
    """2×2 grid of subplots (one per outcome score); x=k, lines=methods, dashed chance."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    nrows, ncols = 2, 2
    fig, axes = plt.subplots(nrows, ncols, figsize=(8.4, 7.2), sharey=False)
    axes_flat = axes.flatten()

    methods = list(data.keys())
    styles = _build_styles(methods)

    for idx, score in enumerate(scores[:4]):
        ax = axes_flat[idx]
        for name in methods:
            d = data.get(name, {}).get(score, {})
            ks = [k for k in NUM_CLASSES if k in d]
            if not ks:
                continue
            ys  = [d[k]["f1"]  for k in ks]
            ers = [d[k]["std"]  for k in ks]
            ax.errorbar(ks, ys, yerr=ers, lw=1.8, markersize=6, capsize=3,
                        label=name, zorder=3, **styles[name])
        ax.set_title(score, fontsize=11)
        ax.set_xticks(NUM_CLASSES)
        ax.grid(True, ls=":", alpha=0.5)
        # x-label only on bottom row
        if idx >= ncols:
            ax.set_xlabel("Number of classes $k$")
        # y-label only on left column
        if idx % ncols == 0:
            ax.set_ylabel("Macro-F1 (cross-validation)")
        # legend in top-left panel only
        if idx == 0:
            ax.legend(fontsize=8, framealpha=0.9)

    # Hide any unused axes (if fewer than 4 scores passed)
    for idx in range(len(scores), nrows * ncols):
        axes_flat[idx].set_visible(False)

    fig.suptitle(title, fontsize=12, y=1.01)
    fig.tight_layout()
    fig.savefig(f"{out_stub}.png", bbox_inches="tight", dpi=200)
    plt.close(fig)
    print(f"figure → {out_stub}.png")


