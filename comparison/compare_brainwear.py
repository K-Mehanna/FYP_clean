"""Comparison utilities for BrainWear 2D: Baseline vs Slot+AA-CBR.

Analogous to compare_pipelines.py but for BrainWear, where the comparison
is shown across k ∈ {2,3,4,5} for each outcome score (QL2, PF2, CF, EF).

Data sources:
  Baseline    -- baseline/brainwear_baseline_cv.json  (generated by brainwear_2d_baseline_cv.py)
  Slot+AA-CBR -- aacbr/leaderboard_trained.json        (eval_trained_brainwear_2d entries)

Outputs (under comparison/):
  figures/compare_brainwear_png.png
  tables/compare_brainwear_png.tex
  tables/compare_brainwear_png.csv
  results/compare_brainwear_png.json
"""

from __future__ import annotations

import csv as csv_mod
import json
import sys
from pathlib import Path

FYP_ROOT = Path(__file__).resolve().parents[1]
if str(FYP_ROOT) not in sys.path:
    sys.path.insert(0, str(FYP_ROOT))

# Reuse style constants from the BraTS comparison module.
from comparison.compare_pipelines import STYLE, chance_level, _fmt, _build_styles  # noqa: F401

# Outcome scores evaluated by both pipelines.
SCORES = ["QL2", "PF2", "CF", "EF"]
NUM_CLASSES = [2, 3, 4, 5]
METHODS_BW = ["Baseline", "Slot+AA-CBR"]

STYLE_BW = {
    "Baseline":    STYLE["Baseline"],
    "Slot+AA-CBR": STYLE["Slot+AA-CBR"],
}

TRAINED_EVAL_SCRIPT = "eval_trained_brainwear_2d"
BASELINE_EVAL_SCRIPT = "baseline_2d_cv"


# ---------------------------------------------------------------------------
# Loaders
# ---------------------------------------------------------------------------

def _load_json(path):
    p = Path(path)
    return json.loads(p.read_text()) if p.exists() else None


def load_baseline_cv(
    lb_path,
    scores: list[str] | None = None,
) -> dict[str, dict[int, dict]]:
    """Load brainwear_baseline_cv.json.

    Returns {score_name: {n_bins: {f1, std, config}}}
    Best-CV-F1 config per (score_name, n_bins) across all pipelines.
    """
    d = _load_json(lb_path)
    if d is None:
        return {}
    rows = [x for x in d
            if x.get("eval_script") == BASELINE_EVAL_SCRIPT
            and x.get("metrics", {}).get("cv_mean_f1") is not None]
    if scores:
        rows = [x for x in rows if x["config"].get("score_name") in scores]

    out: dict[str, dict[int, dict]] = {}
    for x in rows:
        s  = x["config"]["score_name"]
        k  = x["config"]["n_bins"]
        f1 = x["metrics"]["cv_mean_f1"]
        if s not in out:
            out[s] = {}
        if k not in out[s] or f1 > out[s][k]["f1"]:
            out[s][k] = {
                "f1":    float(f1),
                "std":   float(x["metrics"].get("cv_std_f1") or 0.0),
                "config": f"{x['config']['pipeline']} ({x['config']['model']})",
            }
    return out


def load_trained(
    lb_path,
    eval_script: str = TRAINED_EVAL_SCRIPT,
    scores: list[str] | None = None,
    checkpoint: str | None = None,
) -> dict[str, dict[int, dict]]:
    """Load leaderboard_trained.json entries for BrainWear 2D.

    Returns {score_name: {n_bins: {f1, std, config}}}
    Best-CV-F1 AA-CBR config per (score_name, n_bins).
    """
    d = _load_json(lb_path)
    if d is None:
        return {}
    rows = [x for x in d
            if x.get("eval_script") == eval_script
            and x.get("metrics", {}).get("cv_mean_f1") is not None]
    if scores:
        rows = [x for x in rows if x["config"].get("score_name") in scores]
    if checkpoint is not None:
        rows = [x for x in rows if x.get("config", {}).get("checkpoint") == checkpoint]

    out: dict[str, dict[int, dict]] = {}
    for x in rows:
        c  = x["config"]
        s  = c.get("score_name")
        k  = c.get("n_bins")
        f1 = x["metrics"]["cv_mean_f1"]
        if s is None or k is None:
            continue
        if s not in out:
            out[s] = {}
        if k not in out[s] or f1 > out[s][k]["f1"]:
            out[s][k] = {
                "f1":    float(f1),
                "std":   float(x["metrics"].get("cv_std_f1") or 0.0),
                "config": f"{c.get('char_model')}/{c.get('agg_mode')}/{c.get('strategy')}",
            }
    return out


def assemble(
    baseline_lb,
    trained_lb,
    trained_eval_script: str = TRAINED_EVAL_SCRIPT,
    scores: list[str] | None = None,
    checkpoint_labels: dict[str, str] | None = None,
    only_checkpoints: list[str] | None = None,
) -> dict[str, dict]:
    """Load both leaderboards and return a unified data dict.

    Auto-detects unique checkpoints in trained_lb; if more than one is present
    each gets its own key "Slot+AA-CBR (label)".

    Args:
        checkpoint_labels: optional dict mapping checkpoint folder name (e.g.
            ``"brats_png_v14a_gamma4"``) to a custom display label used inside
            the brackets.  Falls back to the folder name when not listed.
        only_checkpoints: optional list of checkpoint folder names to include
            (e.g. ``["brats_png_v14a_gamma4", "brats_png_v20a_attn_skip"]``).
            When ``None`` all checkpoints found in the leaderboard are used.

    Returns:
        {
          "Baseline":             {score: {k: {f1, std, config}}},
          "Slot+AA-CBR (...)":    {score: {k: {f1, std, config}}},  # one per checkpoint
        }
    """
    use_scores = scores or SCORES
    labels = checkpoint_labels or {}

    raw = _load_json(trained_lb) or []
    ckpts = sorted({
        x["config"]["checkpoint"]
        for x in raw
        if x.get("eval_script") == trained_eval_script
        and x.get("config", {}).get("checkpoint")
    })
    if only_checkpoints is not None:
        ckpts = [c for c in ckpts if Path(c).parent.name in only_checkpoints]

    result: dict[str, dict] = {"Baseline": load_baseline_cv(baseline_lb, scores=use_scores)}
    if len(ckpts) <= 1:
        result["Slot+AA-CBR"] = load_trained(
            trained_lb, eval_script=trained_eval_script, scores=use_scores,
            checkpoint=ckpts[0] if ckpts else None)
    else:
        for ckpt in ckpts:
            short = Path(ckpt).parent.name
            display = labels.get(short, short)
            result[f"Slot+AA-CBR ({display})"] = load_trained(
                trained_lb, eval_script=trained_eval_script,
                scores=use_scores, checkpoint=ckpt)
    return result


