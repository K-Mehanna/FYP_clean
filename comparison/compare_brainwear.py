def make_table(data: dict, scores: list[str], title: str, out_path) -> None:
    """LaTeX table: rows = (method × score), columns = k ∈ {2,3,4,5}."""
    head = " & ".join(f"$k={k}$" for k in NUM_CLASSES)
    lines = [
        "% Auto-generated by comparison/compare_brainwear.py -- do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{" + title + ". Macro-F1 (mean $\\pm$ std over 5-fold CV) for "
        "each EORTC outcome score and number of output classes $k$. "
        "\\textbf{Bold} = best per column within each score block. "
        "Chance level is $1/k$.}",
        "\\label{tab:compare-brainwear-png}",
        "\\begin{tabular}{ll" + "c" * len(NUM_CLASSES) + "}",
        "\\toprule",
        "Score & Method & " + head + " \\\\",
        "\\midrule",
    ]

    for si, s in enumerate(scores):
        if si > 0:
            lines.append("\\midrule")
        # Find best per k within this score
        best_per_k: dict[int, str] = {}
        for k in NUM_CLASSES:
            vals = {m: data.get(m, {}).get(s, {}).get(k, {}).get("f1")
                    for m in data}
            vals = {m: v for m, v in vals.items() if v is not None}
            if vals:
                best_per_k[k] = max(vals, key=vals.get)

        for mi, name in enumerate(data):
            cells = []
            for k in NUM_CLASSES:
                d = data.get(name, {}).get(s, {}).get(k)
                txt = _fmt(d)
                if d is not None and best_per_k.get(k) == name:
                    txt = f"\\textbf{{{txt}}}"
                cells.append(txt)
            score_cell = s if mi == 0 else ""
            lines.append(f"{score_cell} & {name} & " + " & ".join(cells) + " \\\\")

        # Chance row per score
        chance_cells = " & ".join(f"{chance_level(k):.3f}" for k in NUM_CLASSES)
        lines.append(f" & \\textit{{Chance}} & {chance_cells} \\\\")

    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
    ]
    Path(out_path).write_text("\n".join(lines) + "\n")
    print(f"table → {out_path}")

