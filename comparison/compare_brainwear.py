def to_dataframe(data: dict, scores: list[str] | None = None):
    """MultiIndex DataFrame: (method, score) rows × k columns."""
    import pandas as pd
    use_scores = scores or SCORES
    cols = [f"k={k}" for k in NUM_CLASSES]
    idx, rows = [], []
    for name in data:
        for s in use_scores:
            d = data.get(name, {}).get(s, {})
            idx.append((name, s))
            rows.append([d.get(k, {}).get("f1", float("nan")) for k in NUM_CLASSES])
    for s in use_scores:
        idx.append(("Chance (1/k)", s))
        rows.append([chance_level(k) for k in NUM_CLASSES])
    return pd.DataFrame(rows, index=pd.MultiIndex.from_tuples(idx, names=["Method", "Score"]),
                        columns=cols)


def config_dataframe(data: dict, scores: list[str] | None = None):
    """Best AA-CBR config string per (score, k)."""
    import pandas as pd
    use_scores = scores or SCORES
    cols = [f"k={k}" for k in NUM_CLASSES]
    idx, rows = [], []
    for name in data:
        for s in use_scores:
            d = data.get(name, {}).get(s, {})
            idx.append((name, s))
            rows.append([d.get(k, {}).get("config", "--") for k in NUM_CLASSES])
    return pd.DataFrame(rows, index=pd.MultiIndex.from_tuples(idx, names=["Method", "Score"]),
                        columns=cols)


# ---------------------------------------------------------------------------
# CSV export
# ---------------------------------------------------------------------------

def write_csv(data: dict, scores: list[str], out_path) -> None:
    """Long-format CSV: one row per (method, score, k)."""
    with open(out_path, "w", newline="") as f:
        w = csv_mod.writer(f)
        w.writerow(["method", "score", "k", "macro_f1", "std", "config", "chance"])
        for name in data:
            for s in scores:
                for k in NUM_CLASSES:
                    d = data.get(name, {}).get(s, {}).get(k)
                    if not d:
                        continue
                    w.writerow([name, s, k, f"{d['f1']:.4f}",
                                f"{d.get('std', 0.0):.4f}",
                                d.get("config", ""),
                                f"{chance_level(k):.4f}"])
    print(f"csv → {out_path}")


