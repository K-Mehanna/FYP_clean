# ---------------------------------------------------------------------------

def rank_scores(
    data: dict[str, dict],
    method: str = "Slot+AA-CBR",
    k: int = 3,
    scores: list[str] | None = None,
) -> list[str]:
    """Rank outcome scores by skill (F1 − 1/k) for *method* at class granularity *k*.

    Scores not present for *method* at *k* are ranked last.
    """
    use_scores = scores or SCORES
    d = data.get(method, {})

    def skill(s):
        entry = d.get(s, {}).get(k)
        if entry is None:
            return -999.0
        return entry["f1"] - chance_level(k)

    return sorted(use_scores, key=skill, reverse=True)


